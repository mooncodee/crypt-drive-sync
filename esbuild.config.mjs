import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { existsSync, readFileSync } from 'node:fs';

// Built-in Google OAuth client: the JSON downloaded from Google Cloud → Clients (type "TVs and Limited Input devices"),
// saved as google-client.json (gitignored). Without it the plugin asks users for their own client.
let client = { id: '', secret: '' };
if (existsSync('google-client.json')) {
	const j = JSON.parse(readFileSync('google-client.json', 'utf8'));
	const c = j.installed ?? j.web ?? j;
	client = { id: c.client_id ?? '', secret: c.client_secret ?? '' };
	if (!client.id) throw new Error('google-client.json: no client_id');
} else {
	console.warn('google-client.json not found: building without a built-in OAuth client');
}

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: false, // readable main.js for reviewers; size is small anyway
	define: { GOOGLE_CLIENT: JSON.stringify(client) },
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
